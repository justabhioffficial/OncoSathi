class PreprocessingService:
    @staticmethod
    def clean_text(text: str) -> str:
        if not text:
            return ""
        text = re.sub(r"\s+", " ", text)
        return text.strip()

    @staticmethod
    def generate_chunk_id(source: str, index: int, text: str) -> str:
        h = hashlib.md5(f"{source}_{index}_{text[:50]}".encode("utf-8")).hexdigest()[:10]
        return f"chk_{h}"

    @classmethod
    def consolidate_knowledge(
        cls,
        ijpc_raw: List[Dict[str, Any]],
        ba_raw: List[Dict[str, Any]],
        bengali_docx_raw: List[Dict[str, Any]],
        tables_csv_raw: List[Dict[str, Any]]
    ) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
        terms_map = {}
        chunks = []
        chunk_idx = 0

        def get_term_key(term_name: str) -> str:
            return re.sub(r"[^a-z0-9]", "", term_name.lower())

        # 1. Process Bengali DOCX (Authoritative for Bengali medical pairs)
        for item in bengali_docx_raw:
            eng = item.get("english_term", "")
            bng = item.get("bengali_term", "")
            sec = item.get("section", "Terminology")
            if eng and bng:
                k = get_term_key(eng)
                if k not in terms_map:
                    terms_map[k] = {
                        "id": f"term_{len(terms_map)+1}",
                        "term": eng,
                        "bengali_term": bng,
                        "category": sec,
                        "medical_definition": f"Standard clinical oncology concept: {eng} ({bng})",
                        "simplified_en": SIMPLIFIED_MAPPINGS.get(k, {}).get("en", f"Medical concept relating to {eng.lower()} in cancer care."),
                        "simplified_bn": SIMPLIFIED_MAPPINGS.get(k, {}).get("bn", bng),
                        "source_document": "3_cancer_terminology_bengali_english.docx",
                        "page_or_section": sec,
                        "related_terms": [],
                        "side_effects": "",
                        "clinical_guidelines": ""
                    }
                else:
                    terms_map[k]["bengali_term"] = bng
                    if not terms_map[k].get("simplified_bn"):
                        terms_map[k]["simplified_bn"] = bng

                chunk_idx += 1
                chunks.append({
                    "id": cls.generate_chunk_id("bengali_docx", chunk_idx, eng),
                    "text": f"Cancer Term: {eng} | Bengali: {bng} | Category: {sec}",
                    "source_document": "3_cancer_terminology_bengali_english.docx",
                    "section": sec,
                    "page": "N/A",
                    "category": sec,
                    "term": eng
                })

        # 2. Process IJPC Glossary
        for item in ijpc_raw:
            p_num = item.get("page", 1)
            raw_text = item.get("text", "")
            lines = raw_text.split("\n")
            for line in lines:
                line = line.strip()
                if ":" in line:
                    parts = line.split(":", 1)
                    t_name = parts[0].strip()
                    defn = parts[1].strip()
                    if len(t_name) > 1 and len(defn) > 5:
                        k = get_term_key(t_name)
                        if k not in terms_map:
                            terms_map[k] = {
                                "id": f"term_{len(terms_map)+1}",
                                "term": t_name,
                                "bengali_term": "",
                                "category": "General Oncology Glossary",
                                "medical_definition": defn,
                                "simplified_en": SIMPLIFIED_MAPPINGS.get(k, {}).get("en", defn),
                                "simplified_bn": SIMPLIFIED_MAPPINGS.get(k, {}).get("bn", ""),
                                "source_document": "1_ijpc_cancer_glossary.pdf",
                                "page_or_section": f"Page {p_num}",
                                "related_terms": [],
                                "side_effects": "",
                                "clinical_guidelines": ""
                            }
                        else:
                            terms_map[k]["medical_definition"] = defn
                            terms_map[k]["source_document"] += " & 1_ijpc_cancer_glossary.pdf"
                            if k in SIMPLIFIED_MAPPINGS:
                                terms_map[k]["simplified_en"] = SIMPLIFIED_MAPPINGS[k]["en"]
                                if not terms_map[k]["simplified_bn"]:
                                    terms_map[k]["simplified_bn"] = SIMPLIFIED_MAPPINGS[k]["bn"]

                        chunk_idx += 1
                        chunks.append({
                            "id": cls.generate_chunk_id("ijpc_glossary", chunk_idx, t_name),
                            "text": f"{t_name}: {defn}",
                            "source_document": "1_ijpc_cancer_glossary.pdf",
                            "section": "Healthcare Glossary",
                            "page": f"Page {p_num}",
                            "category": "Glossary",
                            "term": t_name
                        })

        # 3. Process Ba Oncology Terminology PDF
        for item in ba_raw:
            p_num = item.get("page", 1)
            raw_text = item.get("text", "")
            chunk_idx += 1
            chunks.append({
                "id": cls.generate_chunk_id("ba_oncology", chunk_idx, raw_text),
                "text": raw_text,
                "source_document": "2_medical_oncology_terminology_ba.pdf",
                "section": f"Slide {p_num}",
                "page": f"Slide {p_num}",
                "category": "Clinical Terminology & Etiology",
                "term": "General Oncology"
            })

        # 4. Process Tables CSV
        for item in tables_csv_raw:
            sec = item.get("section", "Table")
            cancer = item.get("category_or_cancer", "")
            term_sub = item.get("term_or_subtype", "")
            detail = item.get("detail", "")
            guide = item.get("guideline", "")
            sides = item.get("side_effects", "")
            full_text = item.get("text", "")
            
            chunk_idx += 1
            chunks.append({
                "id": cls.generate_chunk_id("tables_csv", chunk_idx, full_text),
                "text": full_text,
                "source_document": "4_oncology_comprehensive_tables.csv",
                "section": sec,
                "page": f"Row {item.get('row_idx', 1)}",
                "category": f"{cancer} - {sec}",
                "term": f"{cancer} {term_sub}"
            })

            if "Treatment" in sec or "Protocol" in sec:
                k = get_term_key(term_sub)
                if k not in terms_map and len(term_sub) > 2:
                    terms_map[k] = {
                        "id": f"term_{len(terms_map)+1}",
                        "term": f"{term_sub} ({cancer})",
                        "bengali_term": "",
                        "category": "Cancer Treatment & Drug",
                        "medical_definition": detail,
                        "simplified_en": f"A cancer treatment ({term_sub}) for {cancer}. Guidelines: {guide}. Common side effects: {sides}.",
                        "simplified_bn": f"{cancer}-?? ???? ??????? ???? ({term_sub})? ???????????????????: {sides}?",
                        "source_document": "4_oncology_comprehensive_tables.csv",
                        "page_or_section": sec,
                        "related_terms": [cancer],
                        "side_effects": sides,
                        "clinical_guidelines": guide
                    }

        dictionary_terms = sorted(list(terms_map.values()), key=lambda x: x["term"])
        return dictionary_terms, chunks
